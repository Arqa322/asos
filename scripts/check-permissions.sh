#!/usr/bin/env bash
# mkarchiso copies airootfs with --no-preserve=mode and only applies the modes
# listed in profiledef.sh file_permissions: every executable file in airootfs
# (and every file generated into it by build.sh) must be listed there.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
declare -A listed=()
while read -r path; do listed[$path]=1; done < <(grep -o '\["/[^"]*"\]="[0-9]*:[0-9]*:[0-7]*"' "$ROOT/archiso/profiledef.sh" | sed -E 's/^\["([^"]+)"\].*/\1/')
missing=0
while IFS= read -r f; do
	p=${f#"$ROOT/archiso/airootfs"}
	if [[ -z "${listed[$p]:-}" ]]; then echo "not in file_permissions (would lose its +x bit): $p"; missing=1; fi
done < <(find "$ROOT/archiso/airootfs" -type f -perm -u+x)
for p in /usr/share/asos/pkg-select.sh /usr/share/asos/fetch-zapret.sh /opt/zapret/nfqws; do   # generated by build.sh
	[[ -n "${listed[$p]:-}" ]] || { echo "generated file not in file_permissions: $p"; missing=1; }
done
[[ $missing == 0 ]] && echo "OK: all executables in airootfs are listed in file_permissions"
exit $missing
